export class ToadDialogueSelector {
  constructor(dialogues = TOAD_DIALOGUES, random = Math.random) {
    this.dialogues = dialogues;
    this.random = random;
    this.recent = [];
  }

  pick(category = "normalCorrect") {
    const resolvedCategory = this.dialogues[category]
      ? category
      : "normalCorrect";

    const requested = this.dialogues[resolvedCategory];

    let candidates = requested.filter(
      (text) => !this.recent.includes(text)
    );

    if (!candidates.length) {
      candidates = requested.length
        ? [...requested]
        : [...this.dialogues.normalCorrect];
    }

    const text =
      candidates[Math.floor(this.random() * candidates.length)];

    this.recent = [
      text,
      ...this.recent.filter((item) => item !== text)
    ].slice(0, 3);

    const durationByCategory = {
      wrong: 2400,
      timeout: 2400,
      waterCritical: 2500,
      feverStart: 2400,
      gameOver: 2800,
      gameClear: 2600
    };

    return {
      category: resolvedCategory,
      text,
      duration: durationByCategory[resolvedCategory] ?? 2200
    };
  }
}
